#!/usr/bin/env python3
"""Write web/src/patches.js from fm1patch.py, so the browser patcher and the Python patcher
share one patch table and one set of constants.

    python3 web/export_patches.py && python3 web/build_web.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import fm1patch as p  # noqa: E402


def main():
    spec = {
        "stockSha256": p.STOCK_SHA256,
        "expectedOutSha256": p.EXPECTED_OUT_SHA256,
        "stockVer": p.STOCK_VER.decode(),
        "ver": p.VER.decode(),
        "eqPad": p.EQ_PAD,
        "flashDisk": p.FLASH_DISK,
        "flashSize": p.FLASH_SIZE,
        "appAreaBase": p.APP_AREA_BASE,
        "appBinFw": p.APP_BIN_FW,
        "appSize": p.APP_SIZE,
        "chipKey": p.CHIPKEY,
        "hdrKey": p.HDRKEY,
        "cfgE": p.CFG_E,
        "eqE": p.EQ_E,
        "eqDataLen": p.EQ_DATA_LEN,
        "eqNamePad": p.EQ_NAME_PAD,
        "verOff": p.VER_OFF,
        "patches": [{"name": n, "off": o, "want": w, "new": x} for n, o, w, x in p.PATCHES],
    }
    out = HERE / "src" / "patches.js"
    out.write_text(
        "// Generated by web/export_patches.py from fm1patch.py. Do not edit by hand.\n"
        "var FM1_SPEC = " + json.dumps(spec, indent=1) + ";\n"
        "if (typeof module !== 'undefined') module.exports = FM1_SPEC;\n"
    )
    print(f"wrote {out} ({len(spec['patches'])} patches)")


if __name__ == "__main__":
    main()
